#!/usr/bin/env python3
"""Generate the harness stand-in for the Android `R` class from `app/src/main/res`.

Usage: gen-r.py <res-dir> <out-kt>

The names come from the real resource tree, so the generated class is *not* a blanket "any resource
exists" allowance: referencing a drawable or string the app does not actually ship still fails to
compile, which is the whole reason the harness needs an R at all (the JVM harness has no aapt).

This mirrors only the shape Kotlin sees: `R.<type>.<name>` constants of type `Int`.
"""
import collections
import os
import re
import sys

FILE_TYPES = ("drawable", "mipmap", "layout", "menu", "raw", "anim", "animator", "font", "xml",
              "color", "transition")
VALUE_TYPES = ("string", "color", "style", "dimen", "bool", "integer", "string-array", "array",
               "plurals", "attr", "id")
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def collect(res_dir):
    names = collections.defaultdict(set)
    for dirpath, _, filenames in os.walk(res_dir):
        typ = os.path.basename(dirpath).split("-")[0]
        for fn in filenames:
            path = os.path.join(dirpath, fn)
            if typ in FILE_TYPES:
                base = re.sub(r"\.(xml|png|jpg|jpeg|webp|gif|ttf|otf|mp3|ogg|json)$", "", fn)
                names[typ].add(base)
            if typ != "values" and not typ.endswith("values"):
                continue
            if not fn.endswith(".xml"):
                continue
            src = open(path, encoding="utf-8", errors="replace").read()
            for t in VALUE_TYPES:
                for m in re.finditer(r'<%s\s+[^>]*name="([^"]+)"' % t, src):
                    names[t].add(m.group(1))
            if typ in ("layout",):
                for m in re.finditer(r'@\+id/([A-Za-z0-9_]+)', src):
                    names["id"].add(m.group(1))
    # Layout ids live in layout/*.xml, which the loop above only scans for file-type names.
    for dirpath, _, filenames in os.walk(res_dir):
        if os.path.basename(dirpath).split("-")[0] != "layout":
            continue
        for fn in filenames:
            src = open(os.path.join(dirpath, fn), encoding="utf-8", errors="replace").read()
            for m in re.finditer(r'@\+id/([A-Za-z0-9_]+)', src):
                names["id"].add(m.group(1))
    return names


def emit(names, pkg, out):
    lines = [
        "// GENERATED by tools/jvm-harness/bin/gen-r.py — do not edit.",
        "// Harness stand-in for the aapt-generated `R`. Names come from the real res/ tree so a",
        "// reference to a resource the app does not ship is still a compile error.",
        "package %s" % pkg,
        "",
        "object R {",
    ]
    counter = 0x7f010000
    for typ in sorted(names):
        members = sorted(n for n in names[typ] if n)
        if not members:
            continue
        lines.append("    object %s {" % typ)
        for nm in members:
            # aapt2 keeps resource names verbatim, which for style names can contain dots — an
            # illegal Kotlin identifier. Sanitised here instead of back-ticked; nothing in the app
            # references a resource by a dotted name, and an unknown name still fails to compile.
            key = nm if IDENT.match(nm) else re.sub(r"[^A-Za-z0-9_]", "_", nm)
            if not IDENT.match(key):
                continue
            counter += 1
            lines.append("        const val %s: Int = 0x%x" % (key, counter))
        lines.append("    }")
    lines.append("}")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    return sum(len([n for n in v if n]) for v in names.values())


def main():
    if len(sys.argv) != 3:
        print("usage: gen-r.py <res-dir> <out-kt>", file=sys.stderr)
        return 2
    res_dir, out = sys.argv[1], sys.argv[2]
    if not os.path.isdir(res_dir):
        print("no res dir at %s" % res_dir, file=sys.stderr)
        return 0                      # nothing to stub; the compose step just will not use R
    names = collect(res_dir)
    pkg = "com.studyagent.client"
    count = emit(names, pkg, out)
    print("generated %s: %d entries in %d groups" % (out, count, len(names)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
